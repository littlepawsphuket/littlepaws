"""Bundle the Mac application's allowlisted presentation assets for the staff Worker."""

import base64
import hashlib
import json
from io import BytesIO
from pathlib import Path

from PIL import Image

from app.settings import THEMES


def contents():
    static = Path(__file__).resolve().parents[1] / "app" / "static"
    names = [
        "style.css", "little-paws-logo.png", "little-paws-icon.png", "paw-cursor.png",
        "balen-gucci-relax.webp",
        *(f"{prefix}-{theme}.webp" for theme in THEMES if theme != "classic" for prefix in ("theme", "mascot")),
    ]
    assets = {}
    for name in names:
        raw = (static / name).read_bytes()
        if name == "balen-gucci-relax.webp":
            # Match the banner's display resolution while retaining transparency.
            image = Image.open(BytesIO(raw))
            image.thumbnail((640, 640), Image.Resampling.LANCZOS)
            output = BytesIO()
            image.save(output, format="WEBP", quality=90, method=6)
            raw = output.getvalue()
        assets[name] = [hashlib.sha256(raw).hexdigest()[:16], base64.b64encode(raw).decode("ascii")]
    return "// Generated by python -m cloudflare.sync_ui from the Mac presentation assets.\nexport const uiAssets = " + json.dumps(assets, separators=(",", ":")) + ";\n"


def care_gallery_styles():
    css = (Path(__file__).resolve().parents[1] / "app/static/care-gallery.css").read_text(encoding="utf-8")
    return "// Generated by python -m cloudflare.sync_ui from the shared gallery stylesheet.\nexport const careGalleryCss = " + json.dumps(css, ensure_ascii=False) + ";\n"


if __name__ == "__main__":
    Path(__file__).with_name("ui_assets.mjs").write_text(contents(), encoding="utf-8")
    Path(__file__).with_name("care_gallery_styles.mjs").write_text(care_gallery_styles(), encoding="utf-8")
