export function careTemplates(raw,options) {
  let stored={};
  try { const value=JSON.parse(raw);if(value && typeof value==='object' && !Array.isArray(value))stored=value; } catch {}
  return Object.fromEntries(Object.keys(options).map(key=>[key,
    Array.isArray(stored[key]) ? stored[key].filter(text=>typeof text==='string' && text.trim() && text.length<=500).slice(0,30)
      : [...(defaultCareTemplates[key] || [
        "อัปเดตช่วง"+options[key]+"ของน้องครับ มีเราคอยดูแลอยู่ใกล้ ๆ นะครับ 🐾🩷",
        "วันนี้เก็บภาพตอน"+options[key]+"มาฝากครับ ให้เจ้าของได้หายคิดถึงเจ้าตัวน้อยกันนะครับ 📸🥰",
        "ช่วง"+options[key]+"วันนี้เรียบร้อยแล้วครับ น้องเป็นเด็กน่ารักของบ้านเราเลย 🐶🤍",
        "แวะมาเล่าเรื่อง"+options[key]+"ของน้องครับ เราดูแลตามจังหวะที่น้องสบายใจนะครับ 🏡🩷",
        "ส่งความน่ารักจากช่วง"+options[key]+"มาฝากครับ ขอบคุณที่ไว้ใจให้เราดูแลน้องนะครับ 🐾❤️",
      ])]]));
}

export function validCareTemplates(value,options) {
  if(!value || typeof value!=='object' || Array.isArray(value))return false;
  return Object.keys(value).length<=106 && Object.entries(value).every(([key,items])=>
    Object.hasOwn(options,key) && Array.isArray(items) && items.length<=30 &&
    items.every(text=>typeof text==='string' && text.trim() && text.length<=500));
}
