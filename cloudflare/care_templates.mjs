function decoded(raw) {
  try {const value=JSON.parse(raw);return value && typeof value==='object' && !Array.isArray(value) ? value : {};}catch{return {};}
}
export function careTemplates(raw,options,lang='th') {
  const data=decoded(raw),stored=data.th || data.en ? (data[lang] || {}) : (lang==='th' ? data : {});
  const defaults=lang==='en' ? englishCareTemplates : defaultCareTemplates;
  return Object.fromEntries(Object.keys(options).map(key=>{
    const fallback=defaults[key] || (lang==='en' ? englishCareTemplates.custom : defaultCareTemplates.custom).map((text,index)=>
      lang==='en' ? options[key]+' · '+text : 'ช่วง'+options[key]+' · '+text);
    if(!Array.isArray(stored[key]))return [key,[...fallback]];
    const items=stored[key].filter(text=>typeof text==='string' && text.trim() && text.length<=500).slice(0,30);
    // Expand the original five defaults without altering user-authored templates or intentionally empty lists.
    if(lang==='th' && defaults[key] && items.length===5 && items.every((text,i)=>text===defaults[key][i]))return [key,[...defaults[key]]];
    return [key,items];
  }));
}
export function validCareTemplates(value,options) {
  if(!value || typeof value!=='object' || Array.isArray(value))return false;
  if(Object.hasOwn(value,'th') || Object.hasOwn(value,'en'))return Object.keys(value).every(key=>['th','en'].includes(key)) &&
    Object.values(value).every(items=>items && typeof items==='object' && !Array.isArray(items) && !Object.hasOwn(items,'th') && !Object.hasOwn(items,'en') && validCareTemplates(items,options));
  return Object.keys(value).length<=106 && Object.entries(value).every(([key,items])=>
    Object.hasOwn(options,key) && Array.isArray(items) && items.length<=30 &&
    items.every(text=>typeof text==='string' && text.trim() && text.length<=500));
}
export function mergeCareTemplates(raw,patch) {
  const previous=decoded(raw),stored=previous.th || previous.en ? previous : {th:previous,en:{}};
  const changes=patch.th || patch.en ? patch : {th:patch};
  return {th:{...stored.th,...changes.th},en:{...stored.en,...changes.en}};
}
