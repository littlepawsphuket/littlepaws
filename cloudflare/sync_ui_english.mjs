// Build English UI functions from the same source as Thai. Only source literals
// are translated; API responses, form values, identifiers and user text are not.
import {parse} from 'acorn';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const dictionary=Object.fromEntries((await readFile(new URL('app/en.tsv',root),'utf8')).split('\n').filter(Boolean).map(line=>{
  const i=line.indexOf('\t');return [line.slice(0,i),line.slice(i+1)];
}));
Object.assign(dictionary,JSON.parse(await readFile(new URL('./ui_english.json',import.meta.url),'utf8')));
const targets={staff_ui:'main',coupon_ui:'couponScreen',settings_ui:'settingsScreen',ledger_ui:'ledgerScreen',
  dashboard_ui:'dashboardScreen',report_ui:'reportScreen',account_ui:'accountScreen',backup_ui:'backupScreen'};
const functions={},missing=new Set();
for(const [file,name] of Object.entries(targets)){
  const source=await readFile(new URL(`./${file}.mjs`,import.meta.url),'utf8');
  const ast=parse(source,{ecmaVersion:'latest',sourceType:'module'});
  const declaration=ast.body.map(node=>node.type==='ExportNamedDeclaration'?node.declaration:node)
    .find(node=>node?.type==='FunctionDeclaration' && node.id.name===name);
  if(!declaration)throw Error('Missing UI function '+name);
  const changes=[];
  function walk(node,parent){
    if(!node || typeof node!=='object')return;
    if(node.type==='Literal' && typeof node.value==='string'){
      if(parent?.type==='Property' && parent.key===node && !parent.computed)return;
      const value=node.value;
      if(parent?.type==='ConditionalExpression' && parent.test?.type==='BinaryExpression' &&
          parent.test.left?.name==='lang' && parent.test.right?.value==='en')return;
      const translated=value==='th-TH' && name==='main' ? 'en-GB' : /[ก-๙]/.test(value) ? dictionary[value] : undefined;
      if(/[ก-๙]/.test(value) && translated===undefined)missing.add(value);
      if(translated!==undefined && translated!==value){
        changes.push([node.start,node.end,JSON.stringify(translated)]);
      }
    }
    for(const [key,value] of Object.entries(node)){
      if(['start','end'].includes(key))continue;
      if(Array.isArray(value))value.forEach(child=>walk(child,node));
      else if(value && typeof value==='object')walk(value,node);
    }
  }
  walk(declaration,null);
  let result=source.slice(declaration.start,declaration.end);
  for(const [start,end,text] of changes.sort((a,b)=>b[0]-a[0]))result=result.slice(0,start-declaration.start)+text+result.slice(end-declaration.start);
  parse('('+result+')',{ecmaVersion:'latest'});
  functions[name]=result;
}
if(missing.size)throw Error('Missing English UI phrases: '+JSON.stringify([...missing]));
const generated='// Generated by node cloudflare/sync_ui_english.mjs.\n'+
  'export const englishFunctions='+JSON.stringify(functions)+';\n'+
  'export const uiTranslations='+JSON.stringify(dictionary)+';\n';
const target=new URL('./ui_english_generated.mjs',import.meta.url);
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==generated)throw Error('English UI artifact is stale');
}else await writeFile(target,generated);
console.log('English UI functions verified: '+Object.keys(functions).length);
